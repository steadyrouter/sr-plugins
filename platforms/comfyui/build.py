"""Generate the ComfyUI custom node package: node code, the shared Python client, model lists, pyproject.toml.

The output in dist/comfyui is the whole custom node folder: put it in ComfyUI/custom_nodes/ to try it, publish it
to the Comfy Registry with `comfy node publish` from a repository that holds just this folder (see SUBMIT.md).
ComfyUI has no live dropdowns for nodes, so the model lists are written into _models.py at build time.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from common import DIST, ROOT, Context, copy_tree, fill, fresh_dir

PLATFORM = "comfyui"
HERE = Path(__file__).resolve().parent
# Registry name: the docs advise "Don't include "ComfyUI" in the name", and it cannot change once published.
REGISTRY_NAME = "steadyrouter"
REPOSITORY = "comfyui-steadyrouter"  # the public package repository; ComfyUI repos on GitHub are named so
DISPLAY_NAME = "SteadyRouter"
COMFYUI_TESTED = "0.43.0"
REQUIRES_COMFYUI = ">=0.14.0"  # first release whose comfy_api.latest has everything the nodes use (checked in its source)
CHAT_DEFAULT = "gemini-3.8-flash"
IMAGE_DEFAULT_FAMILY = "nano_banana"  # default model of the "all image models" node
VIDEO_DEFAULT_FAMILY = "seedance"
RESOLUTION_ORDER = ["480p", "540p", "720p", "1080p", "4k"]
TEXT_SUFFIXES = {".py", ".md", ".js"}


def _families(ctx: Context, category: str) -> list[str]:
    return [key for key, fam in ctx.families.items() if fam["category"] == category]


def model_lists(ctx: Context) -> dict:
    """Everything the nodes need from the catalog. Every list must be non-empty."""
    chat = sorted(m["name"] for m in ctx.models("language", platform="chat-tools"))
    images = ctx.models("image", platform="image-tools")
    videos = ctx.models("video", platform="image-tools")
    image_models = {"all": sorted(m["name"] for m in images)}
    image_defaults = {"all": ctx.families[IMAGE_DEFAULT_FAMILY]["default"]}
    for key in _families(ctx, "image"):
        image_models[key] = sorted(m["name"] for m in images if m["family"] == key)
        image_defaults[key] = ctx.families[key]["default"]
    video_models = {"all": sorted(m["name"] for m in videos)}
    video_defaults = {"all": ctx.families[VIDEO_DEFAULT_FAMILY]["default"]}
    for key in _families(ctx, "video"):
        video_models[key] = sorted(m["name"] for m in videos if m["family"] == key)
        video_defaults[key] = ctx.families[key]["default"]
    resolutions, seconds = {}, {}
    for key, names in video_models.items():
        rules = [ctx.video[n] for n in names if n in ctx.video]
        if len(rules) < len(names):  # a model without a rule may take anything the gateway knows
            rules.append({"resolutions": RESOLUTION_ORDER, "seconds": {"min": 1, "max": 16}})
        found = {r for rule in rules for r in rule["resolutions"]}
        resolutions[key] = [r for r in RESOLUTION_ORDER if r in found]
        lengths = [v for rule in rules for v in (rule["seconds"].get("values") or
                                                 [rule["seconds"]["min"], rule["seconds"]["max"]])]
        seconds[key] = [min(lengths), max(lengths)]
    out = {"CHAT_MODELS": chat, "CHAT_DEFAULT": CHAT_DEFAULT, "IMAGE_MODELS": image_models,
           "IMAGE_DEFAULTS": image_defaults, "VIDEO_MODELS": video_models, "VIDEO_DEFAULTS": video_defaults,
           "VIDEO_RESOLUTIONS": resolutions, "VIDEO_SECONDS": seconds}
    empty = [f"{name}[{k}]" for name, value in out.items() if isinstance(value, dict)
             for k, v in value.items() if not v] + ([] if chat else ["CHAT_MODELS"])
    if empty:
        raise ValueError(f"comfyui: empty model lists {empty}; check families.yaml against the catalog")
    return out


def models_py(ctx: Context) -> str:
    test_build = ctx.api_base != ctx.site["api_base"]
    lines = ['"""Generated by platforms/comfyui/build.py from the SteadyRouter catalog. Do not edit."""', "",
             f"VERSION = {json.dumps(ctx.versions[PLATFORM])}",
             f"API_BASE = {json.dumps(ctx.api_base)}",
             "# True only in local test builds pointed at a fake gateway (tools/build.py --base-url). Never released.",
             f"TEST_BUILD = {test_build}", ""]
    for name, value in model_lists(ctx).items():
        lines.append(f"{name} = {json.dumps(value, indent=1)}")
    return "\n".join(lines) + "\n"


def pyproject(ctx: Context) -> str:
    repo = ctx.site["repo_url"].replace("/sr-plugins", f"/{REPOSITORY}")
    return f'''[project]
name = "{REGISTRY_NAME}"
description = "SteadyRouter for ComfyUI: chat, image and video models (Nano Banana, GPT Image, Seedream, Qwen Image, Seedance, Wan, Vidu and hundreds of language models) through one API key. No GPU needed."
version = "{ctx.versions[PLATFORM]}"
license = {{ file = "LICENSE" }}
requires-python = ">=3.10"
dependencies = ["requests"]
classifiers = ["Operating System :: OS Independent"]

[project.urls]
Repository = "{repo}"
Documentation = "{ctx.site['docs_url']}"
"Bug Tracker" = "{repo}/issues"

[tool.comfy]
PublisherId = "steadyrouter"
DisplayName = "{DISPLAY_NAME}"
Icon = "https://raw.githubusercontent.com/{repo.split('github.com/', 1)[1]}/main/icon.svg"
requires-comfyui = "{REQUIRES_COMFYUI}"
includes = []
'''


def build(ctx: Context, out: Path | None = None) -> Path:
    ctx = ctx.for_channel(PLATFORM)
    out = fresh_dir(out or DIST / PLATFORM)
    copy_tree(HERE / "files", out)
    for path in out.rglob("*"):
        if path.is_file() and path.suffix in TEXT_SUFFIXES:
            text = re.sub(r"\{\{comfyui_version\}\}", COMFYUI_TESTED, path.read_text())
            path.write_text(fill(text, ctx))
    copy_tree(ROOT / "core" / "python" / "srclient", out / "srclient")
    (out / "_models.py").write_text(models_py(ctx))
    (out / "pyproject.toml").write_text(pyproject(ctx))
    shutil.copy(ROOT / "brand" / "logo.svg", out / "icon.svg")
    (out / ".gitignore").write_text("__pycache__/\n*.pyc\n")
    return out
