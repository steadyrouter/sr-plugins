"""Generate the n8n community node package: sources, package.json, icons and the shared TS client.

The output in dist/n8n is a plain n8n node project. Compile and lint it with the n8n CLI (`n8n-node build`,
`n8n-node lint`) from a folder that has the dev dependencies installed; see tools/n8n.py.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from common import DIST, ROOT, Context, copy_tree, fresh_dir

PLATFORM = "n8n"
HERE = Path(__file__).resolve().parent
PACKAGE = "n8n-nodes-steadyrouter"
N8N_TESTED = "2.45.7"
# Dev dependencies, pinned to what the package was built and linted with. Nothing is needed at runtime.
DEV_DEPENDENCIES = {"@n8n/node-cli": "0.54.6", "eslint": "9.32.0", "prettier": "3.6.2", "typescript": "5.9.2",
                    "@types/node": "24.19.2"}
TEXT_SUFFIXES = {".ts", ".json", ".md", ".mjs"}


def package_json(ctx: Context) -> dict:
    return {
        "name": PACKAGE,
        "version": ctx.versions[PLATFORM],
        "description": "SteadyRouter for n8n: chat, image and video models through one API key, plus a chat model for AI Agent.",
        "license": "MIT",
        "homepage": ctx.site["docs_url"],
        "keywords": ["n8n-community-node-package", "steadyrouter", "llm", "ai", "image-generation", "video-generation"],
        "author": {"name": ctx.site["brand"], "email": ctx.site["contact"]},
        "repository": {"type": "git", "url": f"git+{ctx.site['repo_url']}.git", "directory": "packages/n8n-nodes-steadyrouter"},
        "scripts": {
            "build": "n8n-node build",
            "lint": "n8n-node lint",
            "lint:fix": "n8n-node lint --fix",
            "release": "n8n-node release",
            "prepublishOnly": "n8n-node prerelease",
        },
        "files": ["dist"],
        "n8n": {
            "n8nNodesApiVersion": 1,
            "aiNodeSdkVersion": 1,
            "strict": True,
            "credentials": ["dist/credentials/SteadyRouterApi.credentials.js"],
            "nodes": ["dist/nodes/SteadyRouter/SteadyRouter.node.js",
                      "dist/nodes/LmChatSteadyRouter/LmChatSteadyRouter.node.js"],
        },
        "devDependencies": DEV_DEPENDENCIES,
        "peerDependencies": {"n8n-workflow": "*", "@n8n/ai-node-sdk": "*"},
    }


def site_ts(ctx: Context) -> str:
    test_build = ctx.api_base != ctx.site["api_base"]
    pricing = f"{ctx.api_base}/api/pricing" if test_build else ctx.site["pricing_api"]
    return (
        "// Generated by platforms/n8n/build.py. Do not edit.\n"
        f"export const API_BASE = {json.dumps(ctx.api_base)};\n"
        f"export const PRICING_API = {json.dumps(pricing)};\n"
        "// True only in local test builds pointed at a fake gateway (tools/build.py --base-url). Never released.\n"
        f"export const TEST_BUILD = {'true' if test_build else 'false'};\n"
    )


def fill_all(text: str, values: dict) -> str:
    """Replace {{key}} placeholders. n8n's own expressions ({{$credentials...}}) are left alone."""
    return re.sub(r"\{\{(\w+)\}\}", lambda m: str(values[m.group(1)]), text)


def build(ctx: Context, out: Path | None = None) -> Path:
    ctx = ctx.for_channel(PLATFORM)
    out = fresh_dir(out or DIST / PLATFORM)
    copy_tree(HERE / "files", out)
    values = {**ctx.site, "api_base": ctx.api_base, "n8n_version": N8N_TESTED}
    for path in out.rglob("*"):
        if path.is_file() and path.suffix in TEXT_SUFFIXES:
            path.write_text(fill_all(path.read_text(), values))
    shared = out / "nodes" / "shared"
    copy_tree(ROOT / "core" / "ts" / "srclient", shared / "srclient")
    (shared / "site.ts").write_text(site_ts(ctx))
    (out / "icons").mkdir(exist_ok=True)  # git keeps no empty folder, so a fresh checkout has none
    for name in ("steadyrouter.svg", "steadyrouter.dark.svg"):  # the logo reads on light and dark backgrounds
        shutil.copy(ROOT / "brand" / "logo.svg", out / "icons" / name)
    (out / "package.json").write_text(json.dumps(package_json(ctx), indent=2) + "\n")
    (out / ".gitignore").write_text("node_modules/\ndist/\n*.tsbuildinfo\n")
    return out
